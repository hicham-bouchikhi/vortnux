"""Generate AOT-safe transport DTOs and endpoint methods from the pinned Nexus v3 contract.

No runtime reflection, no edits to generated files. Unknown inline objects stay JsonElement;
wire enums stay strings so experimental additions do not break deserialization.
"""
import hashlib
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "api/nexus-v3.openapi.yaml"
contract = yaml.safe_load(SPEC.read_text())
schemas = contract["components"]["schemas"]


def identifier(value):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^a-zA-Z0-9]", value) if part)


def flattened(schema):
    result = dict(schema)
    properties = dict(schema.get("properties", {}))
    required = set(schema.get("required", []))
    for item in schema.get("allOf", []):
        item = flattened(schemas[item["$ref"].split("/")[-1]] if "$ref" in item else item)
        properties.update(item.get("properties", {}))
        required.update(item.get("required", []))
    if properties:
        result["properties"] = properties
    result["required"] = required
    return result


def typename(schema):
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        return "string" if schemas[name].get("type") == "string" else identifier(name)
    kind = schema.get("type")
    if kind == "array":
        return f"List<{typename(schema['items'])}>"
    if kind == "string":
        return "string"
    if kind == "integer":
        return "long"
    if kind == "number":
        return "double"
    if kind == "boolean":
        return "bool"
    return "JsonElement"


def fixture(schema, depth=0):
    if depth > 12:
        return None
    if "$ref" in schema:
        return fixture(schemas[schema["$ref"].split("/")[-1]], depth + 1)
    schema = flattened(schema)
    if "enum" in schema:
        return schema["enum"][0]
    if schema.get("properties"):
        return {name: fixture(value, depth + 1) for name, value in schema["properties"].items() if name in schema["required"]}
    return {"string": "fixture", "integer": 1, "number": 1.0, "boolean": False, "array": [], "object": {}}.get(schema.get("type"), {})


for operations in contract["paths"].values():
    for verb, operation in operations.items():
        if verb not in {"get", "post", "put", "patch", "delete"}:
            continue
        for code, response in operation["responses"].items():
            content = response.get("content", {}).get("application/json")
            if str(code).startswith("2") and content and "$ref" not in content["schema"] and content["schema"].get("type") == "object":
                wrapper = identifier(operation["operationId"]) + "Response" + str(code)
                schemas[wrapper] = content["schema"]
                content["schema"] = {"$ref": "#/components/schemas/" + wrapper}


lines = ["// <auto-generated/>", f"// OpenAPI SHA-256: {hashlib.sha256(SPEC.read_bytes()).hexdigest()}",
         "#nullable enable", "using System.Text.Json;", "using System.Text.Json.Serialization;",
         "using System.Text.Json.Serialization.Metadata;", "namespace Vortnux.Core.Generated;", ""]
models = []
for name, raw in schemas.items():
    if raw.get("type") == "string":
        continue
    name = identifier(name)
    models.append(name)
    schema = flattened(raw)
    lines.extend([f"public sealed class {name}", "{"])
    for wire, definition in schema.get("properties", {}).items():
        kind = typename(definition)
        property_name = identifier(wire)
        if property_name == name:
            property_name += "Value"
        required = wire in schema["required"]
        lines.append(f'    [JsonPropertyName("{wire}")]')
        lines.append("    [JsonRequired]" if required else "    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]")
        # Required request members get compiler checks; required response fields get wire checks.
        keyword = "required " if required and name.endswith("Request") else ""
        lines.append(f"    public {keyword}{kind}? {property_name} {{ get; set; }}")
    lines.extend(["    [JsonExtensionData]", "    public Dictionary<string, JsonElement>? AdditionalData { get; set; }", "}", ""])

lines.extend(f"[JsonSerializable(typeof({name}))]" for name in models)
lines.extend(["public partial class NexusV3Json : JsonSerializerContext;", "", "public static class NexusV3Contracts", "{",
              "    public static IReadOnlyList<(Type Type, string Json)> Fixtures { get; } = new (Type, string)[]", "    {"])
lines.extend(f"        (typeof({name}), {json.dumps(json.dumps(fixture(schemas[name]), separators=(',', ':')))})," for name in models)
lines.extend(["    };", "}", "", "public sealed class NexusV3Client(NexusApi transport)", "{"])
for path, operations in contract["paths"].items():
    for verb, operation in operations.items():
        if verb not in {"get", "post", "put", "patch", "delete"}:
            continue
        method = identifier(operation["operationId"]) + "Async"
        variables = re.findall(r"\{([^}]+)\}", path)
        arguments = ["string " + identifier(variable) for variable in variables]
        body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        if body:
            arguments.append(typename(body) + " body")
        arguments.extend(["Dictionary<string, string>? query = null", "CancellationToken cancellationToken = default"])
        response = next((value for code, value in operation["responses"].items() if str(code).startswith("2") and "application/json" in value.get("content", {})), None)
        result = typename(response["content"]["application/json"]["schema"]) if response else None
        if result and result not in models and result != "JsonElement":
            # All referenced response objects are generated; top-level anonymous responses remain JSON.
            result = "JsonElement"
        return_type = f"Task<{result}>" if result else "Task"
        lines.extend([f"    public async {return_type} {method}({', '.join(arguments)})", "    {"])
        route = path
        for variable in variables:
            route = route.replace("{" + variable + "}", "{Uri.EscapeDataString(" + identifier(variable) + ")}")
        lines.append(f'        var path = $"v3{route}";')
        lines.append('        if (query is { Count: > 0 }) path += "?" + string.Join("&", query.Select(pair => Uri.EscapeDataString(pair.Key) + "=" + Uri.EscapeDataString(pair.Value)));')
        if body:
            kind = typename(body)
            if kind == "JsonElement":
                payload = "body"
            else:
                lines.append(f"        var payload = JsonSerializer.SerializeToElement(body, (JsonTypeInfo<{kind}>)NexusV3Json.Default.GetTypeInfo(typeof({kind}))!);")
                payload = "payload"
        else:
            payload = "null"
        call = f"await transport.RequestAsync(HttpMethod.{verb.title()}, path, {payload}, cancellationToken)"
        if result == "JsonElement":
            lines.append(f"        return {call};")
        elif result:
            lines.extend([f"        var response = {call};", f"        return JsonSerializer.Deserialize(response, (JsonTypeInfo<{result}>)NexusV3Json.Default.GetTypeInfo(typeof({result}))!) ?? throw new ModManagerException(\"Empty Nexus response.\");"])
        else:
            lines.append(f"        _ = {call};")
        lines.extend(["    }", ""])
lines.append("}")
destination = ROOT / "src/Vortnux.Core/Generated/NexusV3Client.g.cs"
destination.write_text("\n".join(lines) + "\n")
print(f"Generated {len(models)} DTOs and {sum(len([verb for verb in value if verb in {'get', 'post', 'patch', 'put', 'delete'}]) for value in contract['paths'].values())} methods: {destination.relative_to(ROOT)}")
